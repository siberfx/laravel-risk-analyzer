<?php

use Illuminate\Http\Client\Request;
use Illuminate\Support\Facades\Http;
use Siberfx\RiskAnalyzer\RiskAnalyzer;
use Siberfx\RiskAnalyzer\ScanContext;
use Siberfx\RiskAnalyzer\Support\Lockfiles;

/**
 * @param  array<string, string>  $files
 * @return list<string> "name@version" (+ " dev")
 */
function lockedPackages(array $files, string $reader): array
{
    $context = new ScanContext(app(), test()->project($files), (array) config('risk-analyzer'));

    return array_map(fn (array $package) => $package['name'].'@'.$package['version'].($package['dev'] ? ' dev' : '').' '.$package['source'],
        Lockfiles::{$reader}($context));
}

it('reads yarn.lock v1', function () {
    $lock = <<<'YARN'
        # THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
        # yarn lockfile v1


        "@babel/code-frame@^7.0.0", "@babel/code-frame@^7.10.4":
          version "7.12.13"
          resolved "https://registry.yarnpkg.com/@babel/code-frame/-/code-frame-7.12.13.tgz"
          dependencies:
            "@babel/highlight" "^7.10.4"

        lodash@^4.17.20, lodash@^4.17.21:
          version "4.17.21"

        "string-width-cjs@npm:string-width@^4.2.0":
          version "4.2.3"
        YARN;

    expect(lockedPackages(['yarn.lock' => $lock], 'yarn'))->toBe([
        '@babel/code-frame@7.12.13 yarn.lock',
        'lodash@4.17.21 yarn.lock',
        'string-width@4.2.3 yarn.lock',
    ]);
});

it('reads yarn.lock from Yarn Berry and skips workspaces and patches', function () {
    $lock = <<<'YARN'
        __metadata:
          version: 8
          cacheKey: 10c0

        "@types/node@npm:^20.0.0":
          version: 20.11.5
          resolution: "@types/node@npm:20.11.5"

        "app@workspace:.":
          version: 0.0.0-use.local
          resolution: "app@workspace:."

        "axios@npm:1.6.0, axios@npm:^1.6.0":
          version: 1.6.0
          resolution: "axios@npm:1.6.0"

        "resolve@patch:resolve@npm%3A^1.20.0#optional!builtin<compat/resolve>":
          version: 1.22.8
        YARN;

    expect(lockedPackages(['yarn.lock' => $lock], 'yarn'))->toBe([
        '@types/node@20.11.5 yarn.lock',
        'axios@1.6.0 yarn.lock',
    ]);
});

