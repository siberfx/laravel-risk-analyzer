it('reads the text bun.lock', function () {
    $lock = <<<'BUN'
        {
          "lockfileVersion": 1,
          "workspaces": {
            "": {
              "name": "app",
              "dependencies": { "axios": "^1.6.0", },
            },
          },
          "packages": {
            "axios": ["axios@1.6.0", "", { "dependencies": { "follow-redirects": "^1.15.0" } }, "sha512-a"],
            "@types/node": ["@types/node@20.11.5", "", {}, "sha512-b"],
            "app": ["app@workspace:."],
          },
        }
        BUN;

    expect(lockedPackages(['bun.lock' => $lock], 'bun'))->toBe([
        'axios@1.6.0 bun.lock',
        '@types/node@20.11.5 bun.lock',
    ]);
});

it('merges every JavaScript lockfile and sends them to OSV', function () {
    $root = $this->project([
        'package-lock.json' => json_encode(['lockfileVersion' => 3, 'packages' => ['' => ['name' => 'app'], 'node_modules/axios' => ['version' => '1.6.0']]]),
        'yarn.lock' => "axios@^1.6.0:\n  version \"1.6.0\"\n\nlodash@^4.17.21:\n  version \"4.17.21\"\n",
    ]);
    Http::fake(['api.osv.dev/v1/querybatch' => Http::response(['results' => [[], []]])]);

    app(RiskAnalyzer::class)->scan(only: ['vulnerable-dependency'], baseline: false, basePath: $root);

    Http::assertSent(fn (Request $request) => array_column(array_column($request['queries'], 'package'), 'name') === ['axios', 'lodash']);
});

it('explains that a binary bun.lockb cannot be checked', function () {
    Http::fake();
    $findings = app(RiskAnalyzer::class)->scan(only: ['vulnerable-dependency'], baseline: false, basePath: $this->project(['bun.lockb' => "\0\1binary"]))->findings;

    expect($findings)->toHaveCount(1)
        ->and($findings[0]->severity->value)->toBe('info')
        ->and($findings[0]->message)->toBe('bun.lockb is a binary lockfile and cannot be checked for advisories.');
});
